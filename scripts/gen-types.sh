#!/usr/bin/env bash
# Regenerate ui/src/app/api/generated from the Rust API types.
set -euo pipefail
cd "$(dirname "$0")/.."
rm -rf ui/src/app/api/generated
cargo test -p nixos-manager-core --quiet export_bindings >/dev/null
( echo "// Generated by scripts/gen-types.sh from ts-rs output. Do not edit."
  for f in ui/src/app/api/generated/*.ts; do n=$(basename "$f" .ts); [ "$n" = index ] && continue; echo "export type { $n } from './$n';"; done
) > ui/src/app/api/generated/index.ts
echo "generated $(ls ui/src/app/api/generated | wc -l) files"
